#!/bin/bash
# Milimo Duat dev launcher: picks FREE ports (this machine often has :8000/:5173
# occupied), starts the API + web, wires the frontend to the API, prints URLs.
# Usage: ./scripts/dev.sh [api_port] [web_port]   (omit = auto-pick free ports)
# Stop:  ./scripts/dev.sh stop
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
API_LOG=/tmp/milimo-api.log
WEB_LOG=/tmp/milimo-web.log

free_port() {
  python3 -c "import socket; s=socket.socket(); s.bind(('127.0.0.1',0)); print(s.getsockname()[1])"
}

if [ "${1:-}" = "stop" ]; then
  pkill -f "uvicorn apps.api.main" 2>/dev/null
  pkill -f "vite --config vite.config.localtest" 2>/dev/null
  pkill -f "vite --mode localtest" 2>/dev/null
  echo "stopped duat dev servers"
  exit 0
fi

API_PORT="${1:-$(free_port)}"
WEB_PORT="${2:-$(free_port)}"

pkill -f "uvicorn apps.api.main" 2>/dev/null; sleep 1
DUAT_CORS_ORIGINS="http://localhost:${WEB_PORT},http://127.0.0.1:${WEB_PORT}" \
  nohup python3 -m uvicorn apps.api.main:app --port "$API_PORT" --host 127.0.0.1 \
  > "$API_LOG" 2>&1 &
echo "API starting on :$API_PORT ..."

cat > "$ROOT/apps/web/.env.localtest" <<EOF
# Machine-local override (gitignored). Regenerated by scripts/dev.sh.
VITE_API_BASE_URL=http://127.0.0.1:${API_PORT}
EOF

pkill -f "vite.config.localtest" 2>/dev/null; sleep 1
( cd "$ROOT/apps/web" && nohup npx vite --mode localtest --config vite.config.localtest.ts --port "$WEB_PORT" \
  > "$WEB_LOG" 2>&1 & )
sleep 6
echo "API:      http://127.0.0.1:${API_PORT}/api/health"
echo "API docs: http://127.0.0.1:${API_PORT}/docs   (full interactive system access)"
echo "App:      http://localhost:${WEB_PORT}/"
echo "Logs:     $API_LOG  $WEB_LOG"
